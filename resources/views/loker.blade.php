        // 1. LOGIKA TOMBOL SHARE
        document.querySelectorAll('.share-btn').forEach(button => {
            button.addEventListener('click', async (e) => {
                e.preventDefault();
                const shareUrl = button.getAttribute('data-url');
                const shareTitle = button.getAttribute('data-title');

                if (navigator.share) {
                    try {
                        await navigator.share({
                            title: shareTitle,
                            text: 'Halo! Cek lowongan kerja menarik ini deh:',
                            url: shareUrl,
                        });
                    } catch (err) {
                        console.log('Batal membagikan:', err);
                    }
                } else {
                    try {
                        await navigator.clipboard.writeText(shareUrl);
                        alert('✨ Link lowongan berhasil disalin ke clipboard! Siap dibagikan.');
                    } catch (err) {
                        alert('Gagal menyalin link, silakan salin manual: ' + shareUrl);
                    }
                }
            });
        });

